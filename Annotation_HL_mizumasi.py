from ultralytics import YOLO

# 【重要アドバイス】
# もし前の「best.pt」が『小松菜だけをガッツリ学習したモデル』の場合、
# そこからスタートすると「小松菜バイアス」が強くなり、他の野菜を覚えにくくなります。
# 3種類を公平に覚えさせたい場合は、まっさらな 'yolov8n.pt' または 'yolov8s.pt' から
# スタートすることを強くおすすめします。

# model = YOLO('yolov8n.pt')  # ← 新しく作り直す場合はこっち！
model = YOLO('yolov8m.pt')

model.train(
    data='data.yaml', 

    # ==========================================
    # 🚀 GPU & 基本設定（ここがCPU時代と違います！）
    # ==========================================
    device=0,           # 【超重要】0を指定すると「1枚目のGPU」を使って爆速になります
    batch=-1,           # 【追加】GPUメモリの限界まで一度に画像を読み込む（Auto Batch設定）
                        # ※もしエラーが出る場合は batch=16 や batch=8 に手動で変えてください
    epochs=300,         # 【変更】水増しを激しくする分、学習回数を300回に増やしてじっくり学ばせる
    patience=50,        # 【追加】もし50回連続で精度が上がらなければ、300回を待たずに早期終了（過学習防止）
    imgsz=640,          # GPUに余裕があれば 800 や 1024 もおすすめ
    
    # ---  画像サイズの最適化 ---
    # 【解説】標準は640ですが、葉っぱの細かい「脈」や「ギザギザ」を見分けさせたい場合、
    # 800や1024にすると精度が劇的に上がることがあります。
    # ※ただし、device='cpu'（グラボなし）で1024にすると学習に数日かかる可能性があるため、
    # まずは640または800で試すのが現実的です。

     
    
    # ==========================================
    # 🎨 1. 色と明るさの水増し（日照条件・品種の違い）
    # ==========================================
    hsv_h=0.05,  # 色相のばらつき（デフォルト0.015より少し上げて色変化に強くする）（黄緑から深緑まで対応）
    hsv_s=0.7,   # 彩度（鮮やかさ）のばらつき （鮮やかな葉、枯れかけの葉）
    hsv_v=0.4,   # 明度（明るさ・影）のばらつき （直射日光、日陰）

    # ==========================================
    # 📐 2. 幾何学的な水増し（カメラの角度・距離・風）★大幅強化！
    # ==========================================
    degrees=45.0,       # 【強化】回転（真横に寝ている野菜にも対応）
    translate=0.2,      # 【追加】平行移動（被写体が端っこに寄っている画像を作る）
    scale=0.7,          # 【追加】拡大縮小（近くの大きな葉、遠くの小さな葉を作り出す）
    shear=10.0,         # 【追加】シアー変形（風で斜めに歪んだ葉っぱを再現）
    perspective=0.0005, # 【追加】3D遠近法（カメラを斜めから構えた時のパースをつける）
    flipud=0.5,         # 上下反転
    fliplr=0.5,         # 左右反転
    
    # ==========================================
    # 🧩 3. 隠れ・重なり対策（農業AIの最重要項目）★追加・強化！
    # ==========================================
    mosaic=1.0,         # 4枚の画像を切り貼りして1枚にする
    mixup=0.2,          # 【強化】画像を半透明にして重ねる（重なり合った葉の透け感）
    
    copy_paste=0.3,     # 【超強力・追加】ある画像の野菜を切り抜いて、別の画像に貼り付ける！
                        # （密集した畑の状況をAIが勝手に作り出します）
    
    erasing=0.4,        # 【追加】画像の一部をランダムに黒く塗りつぶす（CutOut）
                        # （泥汚れ、虫食い、他の葉の影で「一部が見えない」状況に強くなる）
    
    # ==========================================
    # 🏁 4. 仕上げ設定
    # ==========================================
    close_mosaic=10,    # 【重要・追加】最後の10エポックはモザイク等の過激な合成をヤメる。
                        # 現実世界の普通の画像に戻して、最終調整をさせるための必須テクニック。

    # フォルダ名を分かりやすく（3種類用に）変更
    name='3veg_max_aug'  
)